#!/usr/bin/env python3
"""Regenerate native/ios/OrunHomework.xcodeproj and its shared scheme.

Run from anywhere:  python3 native/ios/scripts/create-project.py

The project is small and stable on purpose: one app target, no build phases beyond
sources/frameworks/resources, and no CocoaPods/SPM dependencies, so the checked-in
project can be regenerated byte-for-byte instead of being edited by hand.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]  # native/ios

TARGET_NAME = "OrunHomework"
BUNDLE_ID = "com.orunhomework.app"
DEPLOYMENT_TARGET = "15.0"
MARKETING_VERSION = "1.1.0"
BUILD_NUMBER = "1"

SOURCES = [
    "OrunHomeworkApp.swift",
    "Site.swift",
    "WebShellModel.swift",
    "WebShellScripts.swift",
    "WebShellView.swift",
]
RESOURCES = [
    ("Assets.xcassets", "folder.assetcatalog"),
    ("PrivacyInfo.xcprivacy", "text.xml"),
]
PLIST = "Info.plist"

_objects = []


class Ids:
    def __init__(self):
        self.value = 0

    def next(self):
        self.value += 1
        return f"{self.value:024X}"


ids = Ids()


def add(object_id, body):
    _objects.append(f"\t\t{object_id} = {{ {body} }};")


project_id = ids.next()
main_group_id = ids.next()
products_group_id = ids.next()
target_id = ids.next()
product_id = ids.next()
sources_phase_id = ids.next()
frameworks_phase_id = ids.next()
resources_phase_id = ids.next()
project_configs_id = ids.next()
target_configs_id = ids.next()

source_refs = []
source_builds = []
resource_refs = []
resource_builds = []
plist_ref = None

for name in SOURCES:
    ref = ids.next()
    build = ids.next()
    add(ref, f'isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = {TARGET_NAME}/{name}; sourceTree = "<group>";')
    add(build, f"isa = PBXBuildFile; fileRef = {ref};")
    source_refs.append(ref)
    source_builds.append(build)

for name, file_type in RESOURCES:
    ref = ids.next()
    build = ids.next()
    add(ref, f'isa = PBXFileReference; lastKnownFileType = {file_type}; path = {TARGET_NAME}/{name}; sourceTree = "<group>";')
    add(build, f"isa = PBXBuildFile; fileRef = {ref};")
    resource_refs.append(ref)
    resource_builds.append(build)

plist_ref = ids.next()
add(plist_ref, f'isa = PBXFileReference; lastKnownFileType = text.plist.xml; path = {TARGET_NAME}/{PLIST}; sourceTree = "<group>";')

add(product_id, f'isa = PBXFileReference; explicitFileType = wrapper.application; path = {TARGET_NAME}.app; sourceTree = BUILT_PRODUCTS_DIR;')

group_children = source_refs + resource_refs + [plist_ref, products_group_id]
add(main_group_id, f'isa = PBXGroup; children = ({", ".join(group_children)}); sourceTree = "<group>";')
add(products_group_id, f'isa = PBXGroup; name = Products; children = ({product_id}); sourceTree = "<group>";')

add(sources_phase_id, f'isa = PBXSourcesBuildPhase; buildActionMask = 2147483647; files = ({", ".join(source_builds)}); runOnlyForDeploymentPostprocessing = 0;')
add(frameworks_phase_id, "isa = PBXFrameworksBuildPhase; buildActionMask = 2147483647; files = (); runOnlyForDeploymentPostprocessing = 0;")
add(resources_phase_id, f'isa = PBXResourcesBuildPhase; buildActionMask = 2147483647; files = ({", ".join(resource_builds)}); runOnlyForDeploymentPostprocessing = 0;')

project_build_settings = """
				ALWAYS_SEARCH_USER_PATHS = NO;
				CLANG_ANALYZER_NONNULL = YES;
				CLANG_ENABLE_MODULES = YES;
				CLANG_ENABLE_OBJC_ARC = YES;
				CLANG_WARN_DOCUMENTATION_COMMENTS = YES;
				CLANG_WARN_UNGUARDED_AVAILABILITY = YES_AGGRESSIVE;
				COPY_PHASE_STRIP = NO;
				ENABLE_STRICT_OBJC_MSGSEND = YES;
				GCC_C_LANGUAGE_STANDARD = gnu17;
				GCC_NO_COMMON_BLOCKS = YES;
				IPHONEOS_DEPLOYMENT_TARGET = {deployment};
				SDKROOT = iphoneos;
				SWIFT_VERSION = 5.0;
				TARGETED_DEVICE_FAMILY = "1,2";
"""
target_build_settings = """
				ASSETCATALOG_COMPILER_APPICON_NAME = AppIcon;
				CODE_SIGN_STYLE = Automatic;
				CURRENT_PROJECT_VERSION = {build_number};
				DEVELOPMENT_TEAM = "";
				ENABLE_PREVIEWS = YES;
				ENABLE_USER_SCRIPT_SANDBOXING = YES;
				GENERATE_INFOPLIST_FILE = NO;
				INFOPLIST_FILE = {target}/{plist};
				LD_RUNPATH_SEARCH_PATHS = ("$(inherited)", "@executable_path/Frameworks");
				MARKETING_VERSION = {version};
				PRODUCT_BUNDLE_IDENTIFIER = {bundle_id};
				PRODUCT_NAME = "$(TARGET_NAME)";
				SUPPORTS_MACCATALYST = NO;
				SUPPORTS_MAC_DESIGNED_FOR_IPHONE_IPAD = NO;
				SWIFT_EMIT_LOC_STRINGS = YES;
				TARGETED_DEVICE_FAMILY = "1,2";
"""

project_debug_id = ids.next()
project_release_id = ids.next()
target_debug_id = ids.next()
target_release_id = ids.next()


def configuration(object_id, name, settings, extra):
    body = ("isa = XCBuildConfiguration; buildSettings = {"
            + settings + extra
            + "\n\t\t\t};\n\t\t\tname = " + name + ";")
    add(object_id, body)


def project_configuration(object_id, name, extra):
    configuration(object_id, name, project_build_settings.format(deployment=DEPLOYMENT_TARGET), extra)


def target_configuration(object_id, name, extra):
    configuration(object_id, name,
                  target_build_settings.format(build_number=BUILD_NUMBER, version=MARKETING_VERSION,
                                               target=TARGET_NAME, plist=PLIST, bundle_id=BUNDLE_ID),
                  extra)


project_configuration(project_debug_id, "Debug",
                      '\t\t\t\tDEBUG_INFORMATION_FORMAT = dwarf;\n'
                      '\t\t\t\tENABLE_TESTABILITY = YES;\n'
                      '\t\t\t\tGCC_OPTIMIZATION_LEVEL = 0;\n'
                      '\t\t\t\tGCC_PREPROCESSOR_DEFINITIONS = ("DEBUG=1", "$(inherited)");\n'
                      '\t\t\t\tONLY_ACTIVE_ARCH = YES;\n'
                      '\t\t\t\tSWIFT_ACTIVE_COMPILATION_CONDITIONS = DEBUG;\n'
                      '\t\t\t\tSWIFT_OPTIMIZATION_LEVEL = "-Onone";\n')
project_configuration(project_release_id, "Release",
                      '\t\t\t\tDEBUG_INFORMATION_FORMAT = "dwarf-with-dsym";\n'
                      '\t\t\t\tENABLE_NS_ASSERTIONS = NO;\n'
                      '\t\t\t\tSWIFT_COMPILATION_MODE = wholemodule;\n'
                      '\t\t\t\tSWIFT_OPTIMIZATION_LEVEL = "-O";\n'
                      '\t\t\t\tVALIDATE_PRODUCT = YES;\n')
target_configuration(target_debug_id, "Debug", "")
target_configuration(target_release_id, "Release", "")

add(project_configs_id, f'isa = XCConfigurationList; buildConfigurations = ({project_debug_id}, {project_release_id}); defaultConfigurationIsVisible = 0; defaultConfigurationName = Release;')
add(target_configs_id, f'isa = XCConfigurationList; buildConfigurations = ({target_debug_id}, {target_release_id}); defaultConfigurationIsVisible = 0; defaultConfigurationName = Release;')

add(target_id, f'isa = PBXNativeTarget; buildConfigurationList = {target_configs_id}; '
               f'buildPhases = ({sources_phase_id}, {frameworks_phase_id}, {resources_phase_id}); '
               'buildRules = (); dependencies = (); '
               f'name = {TARGET_NAME}; productName = {TARGET_NAME}; productReference = {product_id}; '
               'productType = "com.apple.product-type.application";')

add(project_id, 'isa = PBXProject; attributes = { BuildIndependentTargetsInParallel = 1; LastSwiftUpdateCheck = 2700; LastUpgradeCheck = 2700; TargetAttributes = { '
                f'{target_id} = {{ CreatedOnToolsVersion = 27.0; }}; }}; }}; '
                f'buildConfigurationList = {project_configs_id}; compatibilityVersion = "Xcode 14.0"; '
                'developmentRegion = ko; hasScannedForEncodings = 0; knownRegions = (ko, en, Base); '
                f'mainGroup = {main_group_id}; productRefGroup = {products_group_id}; '
                'projectDirPath = ""; projectRoot = ""; '
                f'targets = ({target_id});')

pbxproj = (
    "// !$*UTF8*$!\n{\n\tarchiveVersion = 1;\n\tclasses = {\n\t};\n\tobjectVersion = 56;\n\tobjects = {\n\n"
    + "\n".join(_objects)
    + f"\n\t}};\n\trootObject = {project_id};\n}}\n"
)

project_dir = ROOT / f"{TARGET_NAME}.xcodeproj"
(project_dir / "xcshareddata" / "xcschemes").mkdir(parents=True, exist_ok=True)
(project_dir / "project.pbxproj").write_text(pbxproj, encoding="utf-8")

scheme = f"""<?xml version="1.0" encoding="UTF-8"?>
<Scheme LastUpgradeVersion="2700" version="1.3">
   <BuildAction parallelizeBuildables="YES" buildImplicitDependencies="YES">
      <BuildActionEntries>
         <BuildActionEntry buildForTesting="YES" buildForRunning="YES" buildForProfiling="YES" buildForArchiving="YES" buildForAnalyzing="YES">
            <BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{target_id}" BuildableName="{TARGET_NAME}.app" BlueprintName="{TARGET_NAME}" ReferencedContainer="container:{TARGET_NAME}.xcodeproj"/>
         </BuildActionEntry>
      </BuildActionEntries>
   </BuildAction>
   <TestAction buildConfiguration="Debug" selectedDebuggerIdentifier="Xcode.DebuggerFoundation.Debugger.LLDB" selectedLauncherIdentifier="Xcode.IDEFoundation.Launcher.LLDB" shouldUseLaunchSchemeArgsEnv="YES"/>
   <LaunchAction buildConfiguration="Debug" selectedDebuggerIdentifier="Xcode.DebuggerFoundation.Debugger.LLDB" selectedLauncherIdentifier="Xcode.IDEFoundation.Launcher.LLDB" launchStyle="0" useCustomWorkingDirectory="NO" ignoresPersistentStateOnLaunch="NO" debugDocumentVersioning="YES" debugServiceExtension="internal" allowLocationSimulation="YES">
      <BuildableProductRunnable runnableDebuggingMode="0">
         <BuildableReference BuildableIdentifier="primary" BlueprintIdentifier="{target_id}" BuildableName="{TARGET_NAME}.app" BlueprintName="{TARGET_NAME}" ReferencedContainer="container:{TARGET_NAME}.xcodeproj"/>
      </BuildableProductRunnable>
   </LaunchAction>
   <ProfileAction buildConfiguration="Release" shouldUseLaunchSchemeArgsEnv="YES" savedToolIdentifier="" useCustomWorkingDirectory="NO" debugDocumentVersioning="YES"/>
   <AnalyzeAction buildConfiguration="Debug"/>
   <ArchiveAction buildConfiguration="Release" revealArchiveInOrganizer="YES"/>
</Scheme>
"""
(project_dir / "xcshareddata" / "xcschemes" / f"{TARGET_NAME}.xcscheme").write_text(scheme, encoding="utf-8")

print(f"Wrote {project_dir.relative_to(pathlib.Path.cwd()) if project_dir.is_relative_to(pathlib.Path.cwd()) else project_dir}")
print(f"  target {TARGET_NAME}  bundle {BUNDLE_ID}  iOS {DEPLOYMENT_TARGET}+  version {MARKETING_VERSION} ({BUILD_NUMBER})")
print(f"  sources {len(SOURCES)}  resources {len(RESOURCES)}  objects {len(_objects)}")
